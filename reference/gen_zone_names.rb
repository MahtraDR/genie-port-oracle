# frozen_string_literal: true

# Generates lib/genie/zone_names.rb (Lich::Genie::ZONE_NAMES) for the Genie port: the
# zone id -> zone name table Remix's $zonename comes from. Remix sets $zonename to the
# <zone name> of the map file its automapper loads (MapForm.cs:650-662 R ->
# GraphForm_ZoneNameChange, AutoMapper.cs:1930-1933 R); the map files are the
# Genie-Maps repo's top-level Map*.xml, whose <zone id> is the genie_zone Lich stamps
# on its rooms.
#
# Run:  ruby reference/gen_zone_names.rb <Genie-Maps checkout> <out.rb>
#       (a GenieClient/Maps checkout; compare <out.rb> with $LICH_WORKTREE/lib/genie/zone_names.rb)
#
# The attribute values are read the way XmlDocument reads them (entities decoded, via
# REXML). Non-ASCII characters are written as [0xNNNN].pack('U') pieces (rubocop
# AsciiOnlySource). Like MapForm.cs:659-662 R, a map whose zone name is empty sets no name,
# so it gets no entry. A duplicate zone id aborts the run.
require 'rexml/document'

abort 'usage: ruby gen_zone_names.rb <Genie-Maps dir> <out.rb>' unless ARGV.length == 2
maps_dir, out_path = ARGV

def ruby_literal(text)
  return text.include?("'") ? text.inspect : "'#{text}'" if text.ascii_only?

  text.each_char.chunk(&:ascii_only?).map do |ascii, chars|
    ascii ? chars.join.inspect : "[#{chars.map { |c| format('0x%04X', c.ord) }.join(', ')}].pack('U*')"
  end.join(' + ')
end

table = {}
files = Dir.glob(File.join(maps_dir, 'Map*.xml'))
abort "no Map*.xml under #{maps_dir}" if files.empty?
files.each do |file|
  head = File.open(file, 'rb') { |io| io.read(4096) }.force_encoding('UTF-8')
  tag = head[/<zone\b[^>]*>/] or abort "#{file}: no <zone> element"
  zone = REXML::Document.new("#{tag}</zone>").root
  id = zone.attributes['id'].to_s
  name = zone.attributes['name'].to_s
  next if name.empty?
  abort "#{file}: duplicate zone id #{id.inspect} (#{table[id][1]})" if table.key?(id)

  table[id] = [name, File.basename(file)]
end

sorted = table.sort_by { |id, _| [id.to_i, id] }
width = sorted.map { |id, _| ruby_literal(id).length }.max # rubocop HashAlignment: table
lines = sorted.map { |id, (name, _)| "      #{ruby_literal(id).ljust(width)} => #{ruby_literal(name)}" }
File.write(out_path, <<~RUBY)
  # frozen_string_literal: true

  # GENERATED by genie-port-lab/reference/gen_zone_names.rb from the Genie-Maps
  # repo's Map*.xml (#{table.size} zones) -- do not edit by hand; re-run the generator.
  module Lich
    module Genie
      # Zone id => zone name: the <zone id> and <zone name> of each Genie map file. Remix's
      # $zonename is the name of the map its automapper loaded (MapForm.cs:650-662 R,
      # AutoMapper.cs:1930-1933 R); the id is the genie_zone Lich stamps on its rooms.
      ZONE_NAMES = {
  #{lines.join(",\n")}
      }.freeze
    end
  end
RUBY
puts "wrote #{out_path}: #{table.size} zones"
